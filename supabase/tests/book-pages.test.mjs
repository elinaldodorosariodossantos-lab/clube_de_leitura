import {beforeEventSchools} from './fixtures/before-event-schools.mjs';
import {legacyContexts} from './fixtures/legacy-policy.mjs';
import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {randomUUID} from 'node:crypto';
import {PGlite} from '../../.qa/postgres/node_modules/@electric-sql/pglite/dist/index.js';

test('livros por paginas: rascunhos, publicacao, progresso, eventos e historico',async()=>{
 const db=new PGlite(),admin=randomUUID(),student=randomUUID();
 const identity=async(id,anonymous)=>{await db.exec('reset role');await db.query("select set_config('request.jwt.claim.sub',$1,false),set_config('request.jwt.claims',$2,false)",[id,JSON.stringify({sub:id,is_anonymous:anonymous})]);await db.exec('set role authenticated');};
 const rpc=async(fn,op,args={})=>(await db.query(`select public.${fn}($1,$2::jsonb) as data`,[op,JSON.stringify(args)])).rows[0].data;
 try{
  await db.exec(`create role anon;create role authenticated;create schema auth;create table auth.users(id uuid primary key,is_anonymous boolean default true);
  create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
  create function auth.jwt() returns jsonb language sql stable as $$select coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb$$;grant usage on schema auth to anon,authenticated;`);
  for(const name of ['202610120001_clube.sql','202610140001_portal.sql','202610150001_leitura.sql','202610150002_admin.sql','202610190001_progressao.sql','202610190002_sequencia.sql'])await db.exec(await readFile(new URL('../migrations/'+name,import.meta.url),'utf8'));
  await db.exec(await readFile(new URL('../instalar-eventos.sql',import.meta.url),'utf8').then(beforeEventSchools));await legacyContexts(db);
  await db.exec(await readFile(new URL('../instalar-eventos.sql',import.meta.url),'utf8').then(beforeEventSchools));await legacyContexts(db);
  await db.query('insert into auth.users values($1,false),($2,true)',[admin,student]);await db.query("insert into public.perfis(id,nome,papel) values($1,'Admin','admin')",[admin]);
  await identity(admin,false);

  const pages=Array.from({length:3},(_,i)=>({id:randomUUID(),text:'Trecho '+i,image:'https://example.test/page-'+i+'.png',layout:['illustration','side','frame'][i]}));
  const draft={id:'book',title:'Livro manual',author:'Autor',content:'',age:'7 anos',level:'facil',ordering:0,active:false,required:true,questions:[{prompt:'',options:['',''],correct:0}],pages:[{...pages[0],text:'',image:''}]};
  await rpc('clube_gestao','story_save',draft);
  let saved=await rpc('clube_gestao','story',{id:'book'});
  assert.deepEqual(saved.pages,draft.pages);assert.equal(saved.questions[0].prompt,'');
  await assert.rejects(rpc('clube_gestao','story_status',{id:'book',active:true}));
  const book={...draft,active:true,pages,questions:[{prompt:'Escolha',options:['Sim','Nao','Talvez'],correct:2}]};
  await assert.rejects(rpc('clube_gestao','story_save',{...book,pages:[]}));
  await assert.rejects(rpc('clube_gestao','story_save',{...book,pages:[{...pages[0],image:'blob:temporary'}]}));
  await rpc('clube_gestao','story_save',book);
  await db.exec('reset role');await db.exec("update public.textos set ativo=false where id<>'book'");
  await identity(student,true);
  const registered=await rpc('clube_portal','register',{name:'Aluno Livro',age:7,school:'Escola Livro',className:'2 ano'});
  await assert.rejects(rpc('clube_gestao','story_save',book));
  await db.exec('reset role');await db.query("update public.alunos set data_nascimento=(current_date-interval '7 years')::date where id=$1",[registered.student.id]);await identity(student,true);
  const attempt=(await rpc('clube_leitura','enter',{level:'facil'})).attempt;
  await assert.rejects(db.query('select * from clube_private.rascunhos_livros'));
  const publicStory=(await db.query('select to_jsonb(t) as data from public.textos t where id=$1',['book'])).rows[0].data;
  assert.ok(!('perguntas_rascunho' in publicStory),'Gabaritos de rascunho nunca ficam na tabela pública');
  assert.deepEqual(attempt.activity.pages,pages);assert.equal(attempt.pageIndex,0);
  await assert.rejects(rpc('clube_leitura','page',{id:attempt.id,pageIndex:2}));
  await assert.rejects(rpc('clube_leitura','stage',{id:attempt.id,stage:'questoes'}));
  await rpc('clube_leitura','page',{id:attempt.id,pageIndex:1});
  assert.equal((await rpc('clube_leitura','get',{id:attempt.id})).pageIndex,1);
  await rpc('clube_leitura','page',{id:attempt.id,pageIndex:0});
  await rpc('clube_leitura','page',{id:attempt.id,pageIndex:1});
  await assert.rejects(rpc('clube_leitura','page',{id:attempt.id,pageIndex:3}));
  await identity(admin,false);
  assert.equal((await rpc('clube_gestao','story',{id:'book'})).pagesProtected,true);
  const reorder=[pages[2],{...pages[0],text:'Editado'},pages[1]];
  await rpc('clube_gestao','story_save',{...book,pages:reorder});
  assert.deepEqual((await rpc('clube_gestao','story',{id:'book'})).pages,reorder);
  await assert.rejects(rpc('clube_gestao','story_save',{...book,pages:[pages[0]]}));
  await db.exec('reset role');await db.query("update public.alunos set data_nascimento=(current_date-interval '7 years')::date where id=$1",[registered.student.id]);await identity(admin,false);
  const dates=(await db.query("select (now()-interval '1 hour')::text as start,(now()+interval '1 day')::text as finish")).rows[0];
  const event=await rpc('clube_eventos','save',{requestId:randomUUID(),name:'Livro Evento',description:'Paginas congeladas',startsAt:dates.start,endsAt:dates.finish,active:true,ageConfigs:[{age:7,levels:[{level:'facil',quantity:1,storyIds:['book']}]}]});
  await rpc('clube_eventos','send',{id:event.id,studentIds:[registered.student.id]});
  await rpc('clube_gestao','story_save',{...book,pages:[pages[0]],confirmPageRemoval:true});
  await identity(student,true);
  const resumed=await rpc('clube_leitura','get',{id:attempt.id});
  assert.deepEqual(resumed.activity.pages,pages);assert.equal(resumed.pageIndex,1);
  await rpc('clube_leitura','page',{id:attempt.id,pageIndex:2});
  await rpc('clube_leitura','stage',{id:attempt.id,stage:'questoes'});
  await rpc('clube_leitura','answer',{id:attempt.id,questionId:attempt.activity.questions[0].id,selected:2});
  assert.equal((await rpc('clube_leitura','finish',{id:attempt.id})).result.points,10);
  const ea=(await rpc('clube_eventos','enter',{id:event.id})).attempt;
  assert.deepEqual(ea.activity.pages,reorder);
  await rpc('clube_leitura','page',{id:ea.id,pageIndex:1});
  assert.equal((await rpc('clube_leitura','get',{id:ea.id})).pageIndex,1);
  await rpc('clube_leitura','page',{id:ea.id,pageIndex:2});
  await rpc('clube_leitura','stage',{id:ea.id,stage:'questoes'});
  await rpc('clube_leitura','answer',{id:ea.id,questionId:ea.activity.questions[0].id,selected:2});
  assert.equal((await rpc('clube_leitura','finish',{id:ea.id})).result.points,10);
  await identity(admin,false);
  const history=await rpc('clube_admin','student',{id:registered.student.id});
  assert.equal(history.attempts.filter(a=>a.includedInTotals).length,2);
  await rpc('clube_gestao','story_save',{...book,active:false,pages:[],confirmPageRemoval:true});
  assert.equal((await rpc('clube_gestao','story',{id:'book'})).pages.length,0);
  await assert.rejects(rpc('clube_gestao','story_status',{id:'book',active:true}));
  await identity(student,true);await assert.rejects(rpc('clube_gestao','story_delete',{id:'book'}));
  await identity(admin,false);
  await assert.rejects(rpc('clube_gestao','story_delete',{id:'missing-book'}));
  assert.equal((await rpc('clube_gestao','story_delete',{id:'book'})).historyPreserved,true);
  assert.equal((await rpc('clube_gestao','story_delete',{id:'book'})).deleted,true);
  assert.ok(!(await rpc('clube_gestao','stories')).some(s=>s.id==='book'));
  assert.equal(await rpc('clube_gestao','story',{id:'book'}),null);
  await assert.rejects(rpc('clube_gestao','story_status',{id:'book',active:true}));
  await assert.rejects(rpc('clube_gestao','story_save',book));
  const preserved=await rpc('clube_admin','student',{id:registered.student.id});
  assert.equal(preserved.attempts.filter(a=>a.includedInTotals).length,2);
  await identity(student,true);
  assert.equal((await rpc('clube_leitura','get',{id:ea.id})).result.points,10);
  assert.equal((await rpc('clube_leitura','get',{id:attempt.id})).result.points,10);
  await db.exec('reset role');
  assert.deepEqual((await db.query('select atividade from clube_private.conteudos_tentativas where tentativa_id=$1',[attempt.id])).rows[0].atividade.pages,pages);
 }finally{await db.close();}
});
